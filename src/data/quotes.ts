const registry=new Map<string,QuoteDefinition>()
const q=(quote:string,comment:string,options:Partial<QuoteDefinition>={}):QuoteDefinition=>{
  const existing=registry.get(quote)
  if(existing)return existing
  const entry=createMeme(quote,comment,options)
  registry.set(quote,entry)
  return entry
}
