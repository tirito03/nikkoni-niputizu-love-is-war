import fs from 'node:fs/promises'
import crypto from 'node:crypto'
let asset=null
for(const extension of ['mp3','ogg','wav']){
  const name=`clubochkom.${extension}`
  try{
    const bytes=await fs.readFile(`public/sounds/${name}`)
    if(bytes.length<100)throw Error(`${name} is empty or invalid`)
    const valid=extension==='mp3'?(bytes.subarray(0,3).toString()==='ID3'||(bytes[0]===255&&(bytes[1]&224)===224)):extension==='ogg'?bytes.subarray(0,4).toString()==='OggS':bytes.subarray(0,4).toString()==='RIFF'&&bytes.subarray(8,12).toString()==='WAVE'
    if(!valid)throw Error(`${name} has an incorrect audio signature`)
    if(asset)throw Error('Keep exactly one clubochkom audio format')
    asset={src:`/sounds/${name}?v=${crypto.createHash('sha256').update(bytes).digest('hex').slice(0,12)}`}
  }catch(error){if(error.code!=='ENOENT')throw error}
}
const output=`// Generated by scripts/sync-voice-asset.mjs. No substitute audio.\nexport const voiceAsset:{src:string}|null=${JSON.stringify(asset)}\n`
const target='src/easter-eggs/voiceAsset.ts'
if(await fs.readFile(target,'utf8').catch(()=>'')!==output)await fs.writeFile(target,output)
console.log(asset?'Voice recording detected locally.':'clubochkom recording not installed; voice controls show its unavailable status.')
